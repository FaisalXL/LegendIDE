#include <iostream>
#include <vector>

int main() {
    std::cout << "🚀 Hello from C++!" << std::endl;
    std::cout << "This is a test of the enhanced run button." << std::endl;
    
    // Simple calculation
    std::vector<int> numbers = {1, 2, 3, 4, 5};
    int total = 0;
    for (int num : numbers) {
        total += num;
    }
    
    std::cout << "Sum of numbers = " << total << std::endl;
    std::cout << "C++ is fast and powerful! ⚡" << std::endl;
    
    return 0;
}